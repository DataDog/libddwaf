"""Turn real ASM (Remote Config) configs into a committable, anonymised set.

Input:  rulesets/asm_org2/*.json  (raw ASM configs fetched from RC, NOT committed)
Output: rulesets/asm_rc/*.json    (committed, used by the "rc*" benchmark rulesets)

The structure (number of custom rules, exclusions, overrides, conditions,
operators, transformers, key paths, regex shapes and lengths) is preserved so
that the WAF does the same amount of work, but identifying content is replaced
deterministically:
  * words (3+ letters) in regexes, phrase/exact lists and rule names are mapped
    to pseudo-words of the same length and case pattern (a small allow-list of
    generic tokens such as "api" or "graphql" is kept);
  * IP addresses / CIDRs are mapped into documentation-like ranges;
  * user identifying tags are replaced.

Usage: uv run sanitize_asm.py [input_dir] [output_dir]
"""

import hashlib
import ipaddress
import json
import re
import sys
from pathlib import Path

KEEP = {
    "api", "graphql", "http", "https", "client", "axios", "version", "type",
    "user", "users", "agent", "signup", "login", "search", "query", "list",
    "status", "config", "comment", "note", "events", "event", "data",
}

WORD = re.compile(r"(?<!\\)[A-Za-z]{3,}")


def pseudo(word: str) -> str:
    if word.lower() in KEEP:
        return word
    h = hashlib.sha256(word.lower().encode()).digest()
    out = []
    for i, ch in enumerate(word):
        c = chr(ord("a") + h[i % len(h)] % 26)
        out.append(c.upper() if ch.isupper() else c)
    return "".join(out)


def map_words(s: str) -> str:
    return WORD.sub(lambda m: pseudo(m.group(0)), s)


def map_ip(s: str) -> str | None:
    try:
        net = ipaddress.ip_network(s, strict=False)
    except ValueError:
        return None
    h = int.from_bytes(hashlib.sha256(s.encode()).digest()[:8], "big")
    if net.version == 4:
        # 100.64.0.0/10 (shared address space): never generated by the benchmark traffic
        base = int(ipaddress.IPv4Address("100.64.0.0")) + (h % (1 << 22))
        addr = ipaddress.IPv4Address(base)
        return str(addr) if "/" not in s else str(ipaddress.ip_network(f"{addr}/{net.prefixlen}", strict=False))
    base = (int(ipaddress.IPv6Address("2001:db8::")) | (h << 32)) & ~((1 << 32) - 1) | (h & 0xFFFFFFFF)
    addr = ipaddress.IPv6Address(base)
    return str(addr) if "/" not in s else str(ipaddress.ip_network(f"{addr}/{net.prefixlen}", strict=False))


def sanitize(obj, path=()):
    if isinstance(obj, dict):
        out = {}
        for k, v in obj.items():
            if k == "usr.email":
                out[k] = "user@example.com"
            elif k == "usr.id":
                out[k] = "user-0"
            else:
                out[k] = sanitize(v, path + (k,))
        return out
    if isinstance(obj, list):
        return [sanitize(v, path + ("[]",)) for v in obj]
    if isinstance(obj, str):
        if path and path[-1] == "regex":
            return map_words(obj)
        if len(path) >= 2 and path[-2] == "list" and path[-1] == "[]":
            ip = map_ip(obj)
            return ip if ip is not None else map_words(obj)
        if path and path[-1] == "name":
            return map_words(obj)
        return obj
    return obj


# The org has several WAF policies, each one assigned to different services; a
# tracer only receives the one of its service. Keep a single (light) policy:
# the others disable 92-149 rules each, and together they would disable most
# of the ruleset, which no real service sees.
SKIP = {
    "policy-by-id-60363ee7-9faf-4740-8dc0-554515fcf372.json",
    "policy-by-id-9d4fe163-3c63-4f07-804a-c19e44fe5102.json",
    # Excludes blk-001-002 (user blocking) for every URI; it would make the
    # blocked-users benchmarks meaningless.
    "exclusion_filters-by-scope-80119736a54b39833e25b488d6086dcc175c3817b1bbed68b52b81fec2c217d2.json",
}


def main() -> None:
    here = Path(__file__).parent
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else here / "rulesets" / "asm_org2"
    dst = Path(sys.argv[2]) if len(sys.argv) > 2 else here / "rulesets" / "asm_rc"
    dst.mkdir(parents=True, exist_ok=True)
    n = 0
    for f in sorted(src.glob("*.json")):
        doc = json.loads(f.read_text())
        if not doc or f.name in SKIP:
            continue
        (dst / f.name).write_text(json.dumps(sanitize(doc), indent=1, sort_keys=False) + "\n")
        n += 1
    print(f"wrote {n} configs to {dst}")


if __name__ == "__main__":
    main()
